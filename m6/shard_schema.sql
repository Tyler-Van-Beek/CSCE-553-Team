CREATE OR REPLACE FUNCTION shard_bucket(event_id integer)
RETURNS integer
LANGUAGE sql
IMMUTABLE
STRICT
AS $$
    SELECT (
        ('x' || substr(md5(event_id::text), 1, 8))::bit(32)::bigint % 64
    )::integer;
$$;


BEGIN;

CREATE TABLE m6_user_reference (
    "UserID" integer PRIMARY KEY
);

CREATE TABLE events_category (
    "CategoryID" integer PRIMARY KEY,
    "Name" varchar(200) NOT NULL UNIQUE
);

CREATE TABLE events_event (
    "EventID" integer PRIMARY KEY,
    "Title" varchar(100) NOT NULL,
    "Description" varchar(500) NOT NULL,
    "Location" varchar(100) NOT NULL,
    "DateTime" timestamptz,
    "EventStatus" boolean NOT NULL,
    "CategoryID_id" integer NOT NULL
        REFERENCES events_category ("CategoryID")
        DEFERRABLE INITIALLY DEFERRED,
    "OrganizerID_id" integer NOT NULL
        REFERENCES m6_user_reference ("UserID")
        DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE events_registration (
    "RegistrationID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "RegistrationStatus" boolean NOT NULL,
    "RegistrationDate" timestamptz NOT NULL,
    "EventID_id" integer NOT NULL
        REFERENCES events_event ("EventID")
        DEFERRABLE INITIALLY DEFERRED,
    "UserID_id" integer NOT NULL
        REFERENCES m6_user_reference ("UserID")
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT unique_user_event_registration UNIQUE ("UserID_id", "EventID_id")
);

CREATE TABLE events_feedback (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Rating" integer NOT NULL,
    "Comments" varchar(500) NOT NULL,
    "Date" timestamptz NOT NULL,
    "EventID_id" integer NOT NULL
        REFERENCES events_event ("EventID")
        DEFERRABLE INITIALLY DEFERRED,
    "UserID_id" integer NOT NULL
        REFERENCES m6_user_reference ("UserID")
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT unique_user_event_feedback UNIQUE ("UserID_id", "EventID_id")
);

CREATE INDEX ON events_category ("Name" varchar_pattern_ops);
CREATE INDEX ON events_event ("CategoryID_id");
CREATE INDEX ON events_event ("OrganizerID_id");
CREATE INDEX ON events_registration ("EventID_id");
CREATE INDEX ON events_registration ("UserID_id");
CREATE INDEX idx_registration_event_registration
    ON events_registration ("EventID_id", "RegistrationID");
CREATE INDEX ON events_feedback ("EventID_id");
CREATE INDEX ON events_feedback ("UserID_id");

COMMIT;
